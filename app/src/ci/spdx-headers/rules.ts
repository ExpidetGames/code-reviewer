// The SPDX license header of the source files: which files carry it, what it looks like in each
// language, and how it is added. The same rules serve the check (spdx-headers.test.ts) and the
// command that writes the headers (cli.ts), so the two cannot disagree.
//
// Node runs this file as it is (type stripping), see cli.ts: relative imports with the .ts
// extension and no TypeScript-only runtime syntax.

export const SPDX_IDENTIFIER = "Apache-2.0";
export const SPDX_HEADER_TEXT = `SPDX-License-Identifier: ${SPDX_IDENTIFIER}`;

/** How many lines from the top of a file may hold the header (a shebang or directive, then the header). */
const HEADER_WINDOW = 3;

export type CommentStyle = "slashes" | "hash" | "block";

// A source file is a file of the project in a programming language or a script, whose language has
// comments. Data and configuration formats are not: JSON has no comments (a header would break it),
// and the YAML, TOML and lock files are read by tools that gain nothing from one. Markdown and the
// license texts are documentation.
const STYLE_BY_EXTENSION: Record<string, CommentStyle> = {
  ".ts": "slashes",
  ".tsx": "slashes",
  ".mts": "slashes",
  ".cts": "slashes",
  ".js": "slashes",
  ".mjs": "slashes",
  ".cjs": "slashes",
  ".css": "block",
  ".py": "hash",
  ".sh": "hash",
};
const STYLE_BY_FILE_NAME: Record<string, CommentStyle> = {
  Dockerfile: "hash",
  Makefile: "hash",
};

// Paths that are never source files of the project, whatever their extension.
const EXCLUDED_SEGMENTS = [
  // Installed or built, never tracked, but present in a working tree.
  "node_modules",
  ".next",
  ".venv",
  "__pycache__",
];
const EXCLUDED_PREFIXES = [
  // Documentation, and the data and scripts that the spikes recorded.
  "docs/",
  // Recorded payloads that tests replay as they are.
  "fakes/fixtures/",
];
// Generated by Next.js (`next typegen`, `next dev`), not authored.
const EXCLUDED_FILE_NAMES = ["next-env.d.ts"];

function fileName(path: string): string {
  return path.slice(path.lastIndexOf("/") + 1);
}

export function commentStyle(path: string): CommentStyle | null {
  const name = fileName(path);
  const byName = STYLE_BY_FILE_NAME[name];
  if (byName) return byName;
  const dot = name.lastIndexOf(".");
  if (dot <= 0) return null;
  return STYLE_BY_EXTENSION[name.slice(dot)] ?? null;
}

/** `path` is relative to the repository root, with forward slashes (as `git ls-files` prints it). */
export function isSourceFile(path: string): boolean {
  if (commentStyle(path) === null) return false;
  if (EXCLUDED_FILE_NAMES.includes(fileName(path))) return false;
  if (EXCLUDED_PREFIXES.some((prefix) => path.startsWith(prefix))) return false;
  const segments = path.split("/");
  return !segments.some((segment) => EXCLUDED_SEGMENTS.includes(segment));
}

function headerLine(style: CommentStyle): string {
  if (style === "slashes") return `// ${SPDX_HEADER_TEXT}`;
  if (style === "hash") return `# ${SPDX_HEADER_TEXT}`;
  return `/* ${SPDX_HEADER_TEXT} */`;
}

/** The identifier of the header in the first lines of the file, or null when there is none. */
export function findHeader(content: string): string | null {
  for (const line of content.split(/\r?\n/).slice(0, HEADER_WINDOW)) {
    const match = /SPDX-License-Identifier:\s*([^\s*]+)/.exec(line);
    if (match) return match[1] ?? null;
  }
  return null;
}

// The leading lines stay where they are when the language or a tool gives them a meaning: a
// shebang (one line), or the parser directives of a Dockerfile (`# syntax=`, `# escape=`,
// `# check=`), which have to come before any other comment.
function leadingLinesToKeep(lines: string[]): number {
  if ((lines[0] ?? "").startsWith("#!")) return 1;
  let count = 0;
  while (/^#\s*(syntax|escape|check)\s*=/i.test(lines[count] ?? "")) count += 1;
  return count;
}

export const HEADER_PROBLEMS = [
  "HEADER_MISSING",
  "HEADER_OTHER_LICENSE",
] as const;
export type HeaderProblem = (typeof HEADER_PROBLEMS)[number];

/**
 * The one rule for "has the right header", used by the check, the command and the test: null when
 * the first lines carry `SPDX-License-Identifier: Apache-2.0`, otherwise why not.
 */
export function headerProblem(content: string): HeaderProblem | null {
  const identifier = findHeader(content);
  if (identifier === null) return "HEADER_MISSING";
  return identifier === SPDX_IDENTIFIER ? null : "HEADER_OTHER_LICENSE";
}

/** Adds the header to a file that has none; returns a file that has one unchanged. */
export function addHeader(content: string, style: CommentStyle): string {
  if (findHeader(content) !== null) return content;
  const eol = content.includes("\r\n") ? "\r\n" : "\n";
  const lines = content === "" ? [] : content.split(eol);
  const header = headerLine(style);
  if (lines.length === 0) return `${header}${eol}`;

  const keep = leadingLinesToKeep(lines);
  const before = lines.slice(0, keep);
  const after = lines.slice(keep);
  // One blank line between the header and what follows, unless the file brings its own. In a hash
  // style file a bare `#` line (the empty line of a comment block) already separates.
  const separated = after[0] === "" || (style === "hash" && after[0] === "#");
  const separator = separated ? [] : [""];
  return [...before, header, ...separator, ...after].join(eol);
}
